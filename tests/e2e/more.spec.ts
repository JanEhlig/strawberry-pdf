import { expect, test } from '@playwright/test'
import { closeAll, inspect, launch, saveWithShortcut, waitForPage, waitForRender, workingCopy } from './helpers'

test.afterEach(closeAll)

test('öffnet eine passwortgeschützte PDF', async () => {
  const { win } = await launch([workingCopy('protected.pdf')])
  const dialog = win.getByRole('dialog', { name: /Passwort erforderlich/ })
  await expect(dialog).toBeVisible({ timeout: 20_000 })
  await dialog.locator('input[type=password]').fill('falsch')
  await dialog.getByRole('button', { name: 'Öffnen' }).click()
  await expect(win.getByRole('dialog', { name: /Passwort erforderlich/ }).getByText(/stimmt nicht/)).toBeVisible()
  await win.screenshot({ path: 'test-results/27-passwort.png' })
  await win.locator('input[type=password]').fill('geheim')
  await win.keyboard.press('Enter')
  await waitForPage(win, 0)
  await expect(win.locator('.page-count')).toContainText('6')
})

test('löscht Seiten und holt sie mit Rückgängig zurück', async () => {
  const file = workingCopy('sample.pdf')
  const { win } = await launch([file])
  await waitForPage(win, 0)
  await win.locator('.thumb').nth(1).click()
  await win.locator('.thumb').nth(2).click({ modifiers: ['Shift'] })
  await expect(win.locator('.thumb.selected')).toHaveCount(2)
  await win.keyboard.press('Delete')
  await expect(win.locator('.page-count')).toContainText('4')
  await win.keyboard.press('Control+z')
  await expect(win.locator('.page-count')).toContainText('6')
  await win.keyboard.press('Control+y')
  await expect(win.locator('.page-count')).toContainText('4')
  await saveWithShortcut(win)
  const result = inspect(file)
  expect(result.pages).toBe(4)
  expect(result.text[1]).toContain('Gedrehte Seite')
})

test('zoomt per Tastatur und Kapsel', async () => {
  const { win } = await launch([workingCopy('sample.pdf')])
  await waitForPage(win, 0)
  const zoom = win.locator('.zoom-value')
  await win.keyboard.press('Control+0')
  await expect(zoom).toHaveText('100 %')
  await win.keyboard.press('Control+=')
  await expect(zoom).toHaveText('110 %')
  await win.getByRole('button', { name: 'Seitenbreite' }).click()
  await expect(zoom).not.toHaveText('110 %')
  await win.locator('.zoom-value').click()
  await win.getByRole('menuitem', { name: '200 %' }).click()
  await expect(zoom).toHaveText('200 %')
  await expect(win.getByRole('button', { name: 'Seitenbreite' })).toHaveAttribute('aria-pressed', 'false')
  await waitForRender(win)
  await win.screenshot({ path: 'test-results/28-zoom-200.png' })
})
